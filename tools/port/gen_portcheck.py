"""Writes src/Src/PortCheckTable.inc: every named code address (constexpr kName = 0x...) in the mod's source that is an
instruction start in Dishonored_DO.exe, with the exe's first 16 bytes there. PortCheck compares the running game with it.
Run from the scratch directory that holds doto.npz (see README), with PYTHONPATH=<repo>/tools."""
import re, os, glob, numpy as np, sys
from pe import PE
home = os.path.expanduser('~')
repo = os.environ.get('REPO', home + '/mnt/Dishonored-Death-of-the-Outsider-VR')
pe = PE(os.environ.get('DOTO_EXE', home + '/mnt/Dishonored_DeathOfTheOutsider/Dishonored_DO.exe'))
rva = np.load('doto.npz')['rva']
FB = np.load('al.npz')['FB']   # DOTO function starts (pipeline.py / buildal.py)
SITE = re.compile(r'(Site|Ret|Insn|Call|Jmp|Patch|Store|Hook)', re.I)
tx = [s for s in pe.sections if s.name == '.text'][0]
def insn_start(v):
    i = np.searchsorted(rva, v); return i < len(rva) and rva[i] == v
rows = {}
for f in sorted(glob.glob(repo + '/src/Src/*.cpp') + glob.glob(repo + '/src/Src/*.h')):
    mod = os.path.splitext(os.path.basename(f))[0]
    for line in open(f, errors='replace'):
        if 'constexpr' not in line: continue
        code = line.split('//')[0]
        for m in re.finditer(r'\b(k\w+)\s*(?:\[\w*\])?\s*=\s*(?:\{\s*)?0x([0-9A-Fa-f]{5,7})\b', code):
            name, v = m.group(1), int(m.group(2), 16)
            if not (tx.va <= v < tx.va + tx.vsize) or not insn_start(v): continue
            j = np.searchsorted(FB, v)
            if not ((j < len(FB) and FB[j] == v) or SITE.search(name)): continue   # struct offsets that happen to fall on code
            if name in ('kOutDefault',): continue   # a gameLocal offset equal to a function start by chance
            rows[(mod, name)] = v
out = ['// Generated by tools/port/gen_portcheck.py from Dishonored_DO.exe 1.145.0.0: do not edit by hand.',
       '// { module, constant, rva, the exe\'s first 16 bytes there }']
for (mod, name), v in sorted(rows.items(), key=lambda x: x[1]):
    b = pe.read(pe.imagebase + v, 16)
    out.append('{ "%s", "%s", 0x%X, { %s } },' % (mod, name, v, ', '.join('0x%02X' % x for x in b)))
open(repo + '/src/Src/PortCheckTable.inc', 'w', newline='\r\n').write('\n'.join(out) + '\n')
print(len(rows), 'entries')
